def parse_marker_message(msg):
    s = str(msg)
    parts = s.split(";")
    out = {"code": parts[0].strip()}
    for p in parts[1:]:
        if "=" in p:
            k, v = p.split("=", 1)
            out[k.strip()] = v.strip()
    return out

def _stream_name_lower(s):
    info = s.get("info", {})
    nm = info.get("name", "")
    if isinstance(nm, (list, tuple, np.ndarray)):
        nm = nm[0] if len(nm) else ""
    return str(nm).strip().lower()

def pick_streams(streams):
    eeg = None
    best = -1

    for s in streams:
        ts = s.get("time_series", None)
        if ts is None:
            continue
        arr = np.asarray(ts)
        ch = 1 if arr.ndim == 1 else arr.shape[1]
        if ch > best:
            eeg = s
            best = ch

    markers = None
    for s in streams:
        ts = s.get("time_series", None)
        if ts is None:
            continue
        arr = np.asarray(ts)
        ch = 1 if arr.ndim == 1 else arr.shape[1]
        if ch != 1:
            continue
        nm = _stream_name_lower(s)
        if ("bart" in nm) or ("marker" in nm) or ("markers" in nm) or ("event" in nm):
            markers = s
            break

    if markers is None:
        for s in streams:
            ts = s.get("time_series", None)
            if ts is None:
                continue
            arr = np.asarray(ts)
            ch = 1 if arr.ndim == 1 else arr.shape[1]
            if ch == 1:
                markers = s
                break

    return eeg, markers

def markers_to_df(marker_stream):
    m_ts = np.asarray(marker_stream["time_stamps"], dtype=float)
    m_val = np.asarray(marker_stream["time_series"], dtype=object)

    rows = []

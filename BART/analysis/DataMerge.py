def process_pair(beh_fp: Path, xdf_fp: Path | None):
    pump_df, trials_df, summary_df = beh_to_pump_table(beh_fp)
    if pump_df is None or len(pump_df) == 0:
        return None

    if xdf_fp is None:
        return pump_df

    try:
        streams, _ = pyxdf.load_xdf(str(xdf_fp))
        eeg_stream, marker_stream = pick_streams(streams)
        if eeg_stream is None or marker_stream is None:
            return pump_df

        raw, eeg_t = build_raw_from_xdf_eeg(eeg_stream)
        raw = preprocess_raw(raw)
        raw.resample(TARGET_SFREQ, verbose=False)
        eeg_t0 = float(eeg_t[0])

        md = markers_to_df(marker_stream)

        ses_mTheta, ses_SD_mThetaB = extract_session_theta_metrics(raw)
        p300 = extract_p300_metrics(raw, md, eeg_t0)
        ev_theta = extract_event_theta_windows(raw, md, eeg_t0)

        pump_theta = theta_before_each_pump(raw, md, eeg_t0)
        trial_theta = trial_theta_from_markers(raw, md, eeg_t0)

        pump_df["ses_mTheta"] = ses_mTheta
        pump_df["ses_SD_mThetaB"] = ses_SD_mThetaB
        for k, v in p300.items():
            pump_df[k] = v
        for k, v in ev_theta.items():
            pump_df[k] = v

        pump_df["tID"] = pd.to_numeric(pump_df["tID"], errors="coerce").astype("Int64")
        pump_df["pump_number"] = pd.to_numeric(pump_df["pump_number"], errors="coerce").astype("Int64")

        if trial_theta is not None and len(trial_theta) > 0:
            tt = trial_theta.copy()
            tt["tID"] = pd.to_numeric(tt["trial"], errors="coerce").astype("Int64")
            tt = tt.drop(columns=["trial"], errors="ignore")

            for c in ["trial_mTheta", "trial_SD_mThetaB"]:
                if c in pump_df.columns:
                    pump_df = pump_df.drop(columns=[c])

            pump_df = pump_df.merge(tt, on="tID", how="left")

        if pump_theta is not None and len(pump_theta) > 0:
            pt = pump_theta.copy()
            pt["tID"] = pd.to_numeric(pt["trial"], errors="coerce").astype("Int64")
            pt["pump_number"] = pd.to_numeric(pt["pump_number"], errors="coerce").astype("Int64")
            pt = pt.drop(columns=["trial"], errors="ignore")

            for c in ["theta_before_pump", "theta_before_pump_Fp1", "theta_before_pump_Fp2", "frontal_asymmetry"]:
                if c in pump_df.columns:
                    pump_df = pump_df.drop(columns=[c])

            pump_df = pump_df.merge(pt, on=["tID", "pump_number"], how="left")

        for c in ["trial_mTheta","trial_SD_mThetaB","theta_before_pump","theta_before_pump_Fp1","theta_before_pump_Fp2","frontal_asymmetry"]:
            if c not in pump_df.columns:
                pump_df[c] = np.nan

        return pump_df

    except Exception as e:
        print("⚠️ XDF failed:", xdf_fp.name, "->", e)
        return pump_df


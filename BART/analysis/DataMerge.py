def extract_survey_row(survey_df, participant_id):
    """
    Convert a survey sheet into one flat row for one participant.
    Keeps all questions as columns.
    Handles:
    - single-row wide format
    - question/response long format
    - generic multi-row fallback
    """
    if survey_df is None or len(survey_df) == 0:
        return None

    df = survey_df.copy()
    df.columns = [str(c).strip() for c in df.columns]

    participant_id = str(participant_id).replace("sub-", "").strip().upper()

    # Case 1: one-row wide format
    if len(df) == 1:
        row = df.iloc[0].to_dict()
        row["pID"] = participant_id
        return row

    # Case 2: question/response long format
    cols_l = {str(c).strip().lower(): c for c in df.columns}
    q_col = None
    r_col = None

    for k in ["question", "item", "prompt"]:
        if k in cols_l:
            q_col = cols_l[k]
            break
    for k in ["response", "answer", "value", "score"]:
        if k in cols_l:
            r_col = cols_l[k]
            break

    if q_col is not None and r_col is not None:
        out = {"pID": participant_id}
        for _, r in df.iterrows():
            q = str(r[q_col]).strip()
            q_clean = re.sub(r"[^A-Za-z0-9]+", "_", q).strip("_").lower()
            out[f"survey_{q_clean}"] = r[r_col]
        return out

    # Case 3: generic multi-row fallback
    out = {"pID": participant_id}
    for i, (_, r) in enumerate(df.iterrows(), start=1):
        for c in df.columns:
            cname = re.sub(r"[^A-Za-z0-9]+", "_", str(c)).strip("_").lower()
            out[f"survey_r{i}_{cname}"] = r[c]
    return out


def parse_marker_message(msg):
    s = str(msg)
    parts = s.split(";")
    out = {"code": parts[0].strip()}
    for p in parts[1:]:
        if "=" in p:
            k, v = p.split("=", 1)
            out[k.strip()] = v.strip()
    return out

def _stream_name_lower(s):
    info = s.get("info", {})
    nm = info.get("name", "")
    if isinstance(nm, (list, tuple, np.ndarray)):
        nm = nm[0] if len(nm) else ""
    return str(nm).strip().lower()

def pick_streams(streams):
    eeg = None
    best = -1

    for s in streams:
        ts = s.get("time_series", None)
        if ts is None:
            continue
        arr = np.asarray(ts)
        ch = 1 if arr.ndim == 1 else arr.shape[1]
        if ch > best:
            eeg = s
            best = ch

    markers = None
    for s in streams:
        ts = s.get("time_series", None)
        if ts is None:
            continue
        arr = np.asarray(ts)
        ch = 1 if arr.ndim == 1 else arr.shape[1]
        if ch != 1:
            continue
        nm = _stream_name_lower(s)
        if ("bart" in nm) or ("marker" in nm) or ("markers" in nm) or ("event" in nm):
            markers = s
            break

    if markers is None:
        for s in streams:
            ts = s.get("time_series", None)
            if ts is None:
                continue
            arr = np.asarray(ts)
            ch = 1 if arr.ndim == 1 else arr.shape[1]
            if ch == 1:
                markers = s
                break

    return eeg, markers

def markers_to_df(marker_stream):
    m_ts = np.asarray(marker_stream["time_stamps"], dtype=float)
    m_val = np.asarray(marker_stream["time_series"], dtype=object)

    rows = []
    for t, v in zip(m_ts, m_val):
        msg = v[0] if isinstance(v, (list, tuple, np.ndarray)) else v
        d = parse_marker_message(msg)
        d["lsltime"] = float(t)
        rows.append(d)

    df = pd.DataFrame(rows)
    for k in ["trial", "pump", "loss", "earnings", "total"]:
        if k in df.columns:
            df[k] = pd.to_numeric(df[k], errors="coerce")
    return df

def build_raw_from_xdf_eeg(eeg_stream):
    data = np.asarray(eeg_stream["time_series"])
    t = np.asarray(eeg_stream["time_stamps"], dtype=float)
    if data.ndim == 1:
        data = data[:, None]
    n_samp, n_ch = data.shape

    sfreq_est = 1.0 / np.median(np.diff(t))
    ch_names = EEG_ORDER[:n_ch] if n_ch <= len(EEG_ORDER) else [f"EEG{ii+1:02d}" for ii in range(n_ch)]
    arr = data.T.astype(np.float32)

    peak = float(np.nanmax(np.abs(arr)))
    if peak > 1e3:
        arr *= 1e-6
    elif peak > 5.0:
        arr *= 1e-3

    info = mne.create_info(ch_names=ch_names, sfreq=sfreq_est, ch_types=["eeg"] * n_ch)
    raw = mne.io.RawArray(arr, info, verbose=False)
    return raw, t


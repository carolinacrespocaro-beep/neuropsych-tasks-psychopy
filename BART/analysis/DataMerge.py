def beh_to_pump_table(beh_fp: Path):
    sheets = read_beh_sheets(beh_fp)
    trials = get_sheet(sheets, ["trials", "trial"])
    summary = get_sheet(sheets, ["summary"])

    if trials is None or len(trials) == 0:
        return None, None, None

    trials = trials.copy()
    bits = parse_bids_bits(beh_fp.name)

    if "exploded" in trials.columns:
        trials["pop"] = trials["exploded"].astype(str).str.upper().isin(["TRUE","1","YES"]).astype(int)
    else:
        trials["pop"] = 0

    if "collected" in trials.columns:
        trials["collect"] = pd.to_numeric(trials["collected"], errors="coerce").fillna(0).astype(int)
    else:
        trials["collect"] = trials["events"].astype(str).str.contains("collect", case=False).astype(int) if "events" in trials.columns else 0

    for c in [
        "trial","pump_count","trial_earnings","loss_if_pop","trial_value","total_earnings",
        "pump_latency_mean","pump_latency_median","pump_latency_first",
        "collect_latency_from_ready","collect_latency_from_trial_start",
        "nf_high_frac","nf_green_success",
        "risk_after_explosion","risk_after_collect","pump_speed_change",
        "nf_mean_normalized"
    ]:
        if c in trials.columns:
            trials[c] = pd.to_numeric(trials[c], errors="coerce")

    if "nf_high_frac" in trials.columns:
        trials["nf_high_fraction"] = pd.to_numeric(trials["nf_high_frac"], errors="coerce")
    elif "nf_high_fraction" not in trials.columns:
        trials["nf_high_fraction"] = np.nan

    if "nf_green_success" in trials.columns and trials["nf_green_success"].notna().any():
        trials["nf_green_success"] = pd.to_numeric(trials["nf_green_success"], errors="coerce")
    else:
        trials["nf_green_success"] = np.where(trials["nf_high_fraction"] > 0.75, 1, 0).astype(int) if "nf_high_fraction" in trials.columns else np.nan

    block_col = "block" if "block" in trials.columns else None
    if block_col is not None:
        trials = trials.sort_values([block_col, "trial"], kind="mergesort") if "trial" in trials.columns else trials
        g = trials.groupby(block_col)["nf_green_success"]
        trials["nf_bonus_awarded_trial"] = ((g.shift(0)==1) & (g.shift(1)==1) & (g.shift(2)==1)).astype(int)
    else:
        trials["nf_bonus_awarded_trial"] = 0

    if "pump_count" in trials.columns and block_col is not None and "trial" in trials.columns:
        trials["prev_pumps"] = trials.groupby(block_col)["pump_count"].shift(1)
        prev_pop = trials.groupby(block_col)["pop"].shift(1)
        prev_collect = trials.groupby(block_col)["collect"].shift(1)

        trials["risk_after_explosion"] = np.where(prev_pop == 1, trials["pump_count"] - trials["prev_pumps"], np.nan)
        trials["risk_after_collect"] = np.where(prev_collect == 1, trials["pump_count"] - trials["prev_pumps"], np.nan)

        if "pump_latency_mean" in trials.columns:
            trials["pump_speed_change"] = trials["pump_latency_mean"] - trials.groupby(block_col)["pump_latency_mean"].shift(1)
        else:
            trials["pump_speed_change"] = np.nan
    else:
        if "risk_after_explosion" not in trials.columns:
            trials["risk_after_explosion"] = np.nan
        if "risk_after_collect" not in trials.columns:
            trials["risk_after_collect"] = np.nan
        if "pump_speed_change" not in trials.columns:
            trials["pump_speed_change"] = np.nan

    sesPoints = trials["total_earnings"].dropna().max() if "total_earnings" in trials.columns else np.nan
    exp_N = int(trials["pop"].sum())
    collect_N = int(trials["collect"].sum())
    tN = int(len(trials))
    exp_rate = exp_N / tN if tN else np.nan
    collect_rate = collect_N / tN if tN else np.nan
    bonus_N = int(trials["nf_bonus_awarded_trial"].sum()) if "nf_bonus_awarded_trial" in trials.columns else 0

    smPmp = float(trials["pump_count"].mean()) if "pump_count" in trials.columns else np.nan
    SD_smPmp = float(trials["pump_count"].std(ddof=1)) if "pump_count" in trials.columns else np.nan

    trials["adjusted_pumps_trial"] = trials["pump_count"] if "pump_count" in trials.columns else np.nan
    smADJ_pmp = float(trials["adjusted_pumps_trial"].mean()) if "adjusted_pumps_trial" in trials.columns else np.nan
    SD_smADJ_pmp = float(trials["adjusted_pumps_trial"].std(ddof=1)) if "adjusted_pumps_trial" in trials.columns else np.nan

    mpmpL = float(trials["pump_latency_mean"].mean()) if "pump_latency_mean" in trials.columns else np.nan
    SD_mpmpL = float(trials["pump_latency_mean"].std(ddof=1)) if "pump_latency_mean" in trials.columns else np.nan
    medpmpL = float(trials["pump_latency_median"].mean()) if "pump_latency_median" in trials.columns else np.nan
    SD_medpmpL = float(trials["pump_latency_median"].std(ddof=1)) if "pump_latency_median" in trials.columns else np.nan

    def _get_scalar_from_sources(keys, sources):
        for df in sources:
            if df is None or len(df) == 0:
                continue
            cols_lut = {str(c).strip().lower(): c for c in df.columns}
            for k in keys:
                kk = str(k).strip().lower()
                if kk in cols_lut:
                    col = cols_lut[kk]
                    ser = pd.to_numeric(df[col], errors="coerce")
                    if ser.notna().any():
                        return float(ser.dropna().iloc[0])
        return np.nan

    sources = [trials, summary]

    baseline_cols = {
        "baseline_eo_mu": _get_scalar_from_sources(
            ["baseline_eo_mu", "baseline_pre_eo_mu", "pretask_eob_avgtheta", "pretask_eo_avgtheta"], sources),
        "baseline_ec_mu": _get_scalar_from_sources(
            ["baseline_ec_mu", "baseline_pre_ec_mu", "pretask_ecb_avgtheta", "pretask_ec_avgtheta"], sources),
        "baseline_conc_mu": _get_scalar_from_sources(
            ["baseline_conc_mu", "baseline_pre_conc_mu", "pretask_cb_avgtheta", "pretask_conc_avgtheta"], sources),

        "baseline_post_eo_mu": _get_scalar_from_sources(
            ["baseline_post_eo_mu", "posttask_eob_avgtheta", "post_eob_avgtheta", "posttask_eo_avgtheta"], sources),
        "baseline_post_ec_mu": _get_scalar_from_sources(
            ["baseline_post_ec_mu", "posttask_ecb_avgtheta", "post_ecb_avgtheta", "posttask_ec_avgtheta"], sources),
        "baseline_post_conc_mu": _get_scalar_from_sources(
            ["baseline_post_conc_mu", "posttask_cb_avgtheta", "post_cb_avgtheta", "posttask_conc_avgtheta"], sources),
    }

    pump_rows = []
    for _, tr in trials.iterrows():
        n = int(tr["pump_count"]) if pd.notna(tr.get("pump_count", np.nan)) else 0
        if n <= 0:
            continue

        lat_list = safe_json_list(tr.get("pump_latencies_json", None))

        for p in range(1, n + 1):
            row = {}

            row["pID"] = normalize_pid_series(pd.Series([bits["sub"]]))[0]
            row["cond"] = bits["condition"]
            row["sID"] = bits["ses"]
            row["ses_num"] = bits["ses_num"]

            row["pPoints"] = np.nan
            row["risk_group"] = np.nan

            row["sesPoints"] = sesPoints
            row["exp_N"] = exp_N
            row["collect_N"] = collect_N
            row["bonus_N"] = bonus_N
            row["exp_rate"] = exp_rate
            row["collect_rate"] = collect_rate
            row["smPmp"] = smPmp
            row["SD_smPmp"] = SD_smPmp
            row["smADJ_pmp"] = smADJ_pmp
            row["SD_smADJ_pmp"] = SD_smADJ_pmp
            row["mpmpL"] = mpmpL
            row["SD_mpmpL"] = SD_mpmpL
            row["medpmpL"] = medpmpL
            row["SD_medpmpL"] = SD_medpmpL

            row["pretask_EOB_avgTheta"]  = baseline_cols.get("baseline_eo_mu", np.nan)
            row["posttask_EOB_avgTheta"] = baseline_cols.get("baseline_post_eo_mu", np.nan)
            row["pretask_ECB_avgTheta"]  = baseline_cols.get("baseline_ec_mu", np.nan)
            row["posttask_ECB_avgTheta"] = baseline_cols.get("baseline_post_ec_mu", np.nan)
            row["pretask_CB_avgTheta"]   = baseline_cols.get("baseline_conc_mu", np.nan)
            row["posttask_CB_avgTheta"]  = baseline_cols.get("baseline_post_conc_mu", np.nan)

            row["tID"] = int(tr["trial"]) if "trial" in tr and pd.notna(tr["trial"]) else np.nan
            row["pop"] = int(tr["pop"])
            row["collect"] = int(tr["collect"])
            row["pmp_count"] = int(tr["pump_count"]) if pd.notna(tr.get("pump_count", np.nan)) else np.nan
            row["t_earned"] = float(tr["trial_earnings"]) if "trial_earnings" in tr and pd.notna(tr["trial_earnings"]) else np.nan
            row["t_loss"] = float(tr["loss_if_pop"]) if "loss_if_pop" in tr and pd.notna(tr["loss_if_pop"]) else np.nan

            row["collectL_trial"] = float(tr["collect_latency_from_trial_start"]) if "collect_latency_from_trial_start" in tr and pd.notna(tr["collect_latency_from_trial_start"]) else np.nan
            row["collectL_ready"] = float(tr["collect_latency_from_ready"]) if "collect_latency_from_ready" in tr and pd.notna(tr["collect_latency_from_ready"]) else np.nan

            row["nf_high_fraction"] = float(tr["nf_high_fraction"]) if "nf_high_fraction" in tr and pd.notna(tr["nf_high_fraction"]) else np.nan
            row["nf_green_success"] = int(tr["nf_green_success"]) if "nf_green_success" in tr and pd.notna(tr["nf_green_success"]) else np.nan

            row["risk_after_explosion"] = float(tr.get("risk_after_explosion", np.nan)) if pd.notna(tr.get("risk_after_explosion", np.nan)) else np.nan
            row["risk_after_collect"] = float(tr.get("risk_after_collect", np.nan)) if pd.notna(tr.get("risk_after_collect", np.nan)) else np.nan
            row["pump_speed_change"] = float(tr.get("pump_speed_change", np.nan)) if pd.notna(tr.get("pump_speed_change", np.nan)) else np.nan

            row["pump_number"] = int(p)
            row["pmpID"] = f"{bits['sub']}_{bits['ses']}_T{int(row['tID'])}_P{p}" if pd.notna(row["tID"]) else f"{bits['sub']}_{bits['ses']}_P{p}"
            row["pmpL"] = float(lat_list[p-1]) if isinstance(lat_list, list) and len(lat_list) >= p else np.nan

            row["ses_mTheta"] = np.nan
            row["ses_SD_mThetaB"] = np.nan
            row["ses_avgP300_All"] = np.nan
            row["ses_avgP300_Fz"] = np.nan
            row["ses_avgP300_FCz"] = np.nan
            row["ses_avgP300_Cz"] = np.nan
            row["ses_avgP300_Pz"] = np.nan

            row["pre200_pop_Theta"] = np.nan
            row["post200_pop_Theta"] = np.nan
            row["pre200_collect_Theta"] = np.nan
            row["post200_collect_Theta"] = np.nan
            row["pre200_pmp_Theta"] = np.nan

            row["theta_before_pump"] = np.nan
            row["theta_before_pump_Fp1"] = np.nan
            row["theta_before_pump_Fp2"] = np.nan
            row["frontal_asymmetry"] = np.nan

            row["trial_mTheta"] = np.nan
            row["trial_SD_mThetaB"] = np.nan

            pump_rows.append(row)

    pump_df = pd.DataFrame(pump_rows)
    return pump_df, trials, summary


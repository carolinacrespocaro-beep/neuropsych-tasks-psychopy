def normalize_pid_series(s):
    s = s.astype(str).str.strip().str.upper()

    s = s.str.replace("SUB-", "", regex=False)
    s = s.str.replace("SUB_", "", regex=False)
    s = s.str.replace("PARTICIPANT", "", regex=False)
    s = s.str.replace("PID", "", regex=False)
    s = s.str.replace("P_ID", "", regex=False)
    s = s.str.replace("SUBJECT_ID", "", regex=False)

    nums = s.str.extract(r"(\d+)")[0]
    out = nums.fillna("").apply(lambda x: f"P{int(x):03d}" if x != "" else np.nan)
    out = out.where(out.notna(), s)
    return out


def compute_theta_power_window(raw_theta, sample, tmin_s, tmax_s, picks):
    sf = raw_theta.info["sfreq"]
    start = int(sample + np.round(tmin_s * sf))
    stop  = int(sample + np.round(tmax_s * sf))
    start = max(start, 0)
    stop  = min(stop, raw_theta.n_times)
    if stop <= start + 2:
        return np.nan
    seg = raw_theta.get_data(picks=picks, start=start, stop=stop)
    return float(np.mean(seg**2))

def extract_session_theta_metrics(raw):
    rtheta = raw.copy().filter(THETA_BAND[0], THETA_BAND[1], picks="eeg", verbose=False)
    picks = [raw.ch_names.index(ch) for ch in FRONTAL_THETA_CHS if ch in raw.ch_names]
    if len(picks) == 0:
        return np.nan, np.nan
    X = rtheta.get_data(picks=picks)
    theta_ts = np.mean(X**2, axis=0)
    return float(np.mean(theta_ts)), float(np.std(theta_ts, ddof=1))

def extract_p300_metrics(raw, md, eeg_t0):
    keys = ["ses_avgP300_All","ses_avgP300_Fz","ses_avgP300_FCz","ses_avgP300_Cz","ses_avgP300_Pz"]
    if "code" not in md.columns:
        return {k: np.nan for k in keys}

    exp = md[md["code"].astype(str).str.upper().eq("BART_EXPLODE")].copy()
    if len(exp) == 0:
        return {k: np.nan for k in keys}

    sf = raw.info["sfreq"]
    exp = exp.dropna(subset=["lsltime"]).copy()
    exp["sample"] = exp["lsltime"].apply(lambda t: lsltime_to_sample(float(t), eeg_t0, sf)).astype(int)

    min_samp = int(np.ceil((-ERP_TMIN) * sf))
    exp = exp[(exp["sample"] >= min_samp) & (exp["sample"] < raw.n_times)].copy()
    if len(exp) == 0:
        return {k: np.nan for k in keys}

    events = np.c_[exp["sample"].to_numpy(), np.zeros(len(exp), int), np.ones(len(exp), int)]
    epochs = mne.Epochs(
        raw, events, event_id={"EXPLODE": 1},
        tmin=ERP_TMIN, tmax=ERP_TMAX, baseline=ERP_BASELINE,
        preload=True, reject_by_annotation=True, verbose=False
    )
    if len(epochs) == 0:
        return {k: np.nan for k in keys}

    ev = epochs.average()
    times = ev.times
    m1 = np.argmin(np.abs(times - P3_WIN[0]))
    m2 = np.argmin(np.abs(times - P3_WIN[1]))

    out = {}
    vals = []
    for ch in ["Fz","FCz","Cz","Pz"]:
        k = f"ses_avgP300_{ch}"
        if ch in ev.ch_names:
            idx = ev.ch_names.index(ch)
            erp_uV = ev.data[idx] * 1e6
            p3 = float(np.max(erp_uV[m1:m2]))
            out[k] = p3
            vals.append(p3)
        else:
            out[k] = np.nan
    out["ses_avgP300_All"] = float(np.nanmean(vals)) if len(vals) else np.nan
    return out

def extract_event_theta_windows(raw, md, eeg_t0):
    rtheta = raw.copy().filter(THETA_BAND[0], THETA_BAND[1], picks="eeg", verbose=False)
    sf = raw.info["sfreq"]
    picks = [raw.ch_names.index(ch) for ch in FRONTAL_THETA_CHS if ch in raw.ch_names]
    if len(picks) == 0:
        return {
            "pre200_pop_Theta": np.nan, "post200_pop_Theta": np.nan,
            "pre200_collect_Theta": np.nan, "post200_collect_Theta": np.nan,
            "pre200_pmp_Theta": np.nan,
        }

    def _mean_prepost(code, pre=True):
        d = md[md["code"].astype(str).str.upper().eq(code)].dropna(subset=["lsltime"]).copy()
        if len(d) == 0:
            return np.nan
        d["sample"] = d["lsltime"].apply(lambda t: lsltime_to_sample(float(t), eeg_t0, sf)).astype(int)
        vals = []
        for s in d["sample"].tolist():
            v = compute_theta_power_window(rtheta, s, -WIN200, 0.0, picks) if pre else compute_theta_power_window(rtheta, s, 0.0, WIN200, picks)
            vals.append(v)
        return float(np.nanmean(vals)) if len(vals) else np.nan

    return {
        "pre200_pop_Theta": _mean_prepost("BART_EXPLODE", pre=True),
        "post200_pop_Theta": _mean_prepost("BART_EXPLODE", pre=False),
        "pre200_collect_Theta": _mean_prepost("BART_COLLECT", pre=True),
        "post200_collect_Theta": _mean_prepost("BART_COLLECT", pre=False),
        "pre200_pmp_Theta": _mean_prepost("BART_PUMP", pre=True),
    }

def theta_before_each_pump(raw, md, eeg_t0):
    pumps = md[md["code"].astype(str).str.upper().eq("BART_PUMP")].copy()
    if len(pumps) == 0 or ("trial" not in pumps.columns) or ("pump" not in pumps.columns):
        return pd.DataFrame(columns=["trial","pump_number","theta_before_pump","theta_before_pump_Fp1","theta_before_pump_Fp2","frontal_asymmetry"])

    rtheta = raw.copy().filter(THETA_BAND[0], THETA_BAND[1], picks="eeg", verbose=False)
    sf = raw.info["sfreq"]

    pumps["trial"] = pd.to_numeric(pumps["trial"], errors="coerce")
    pumps["pump_number"] = pd.to_numeric(pumps["pump"], errors="coerce")
    pumps = pumps.dropna(subset=["trial","pump_number","lsltime"]).copy()

    pumps["trial"] = pumps["trial"].astype(int)
    pumps["pump_number"] = pumps["pump_number"].astype(int)
    pumps["sample"] = pumps["lsltime"].apply(lambda t: lsltime_to_sample(float(t), eeg_t0, sf)).astype(int)

    min_samp = int(np.ceil(WIN200 * sf))
    pumps = pumps[(pumps["sample"] >= min_samp) & (pumps["sample"] < raw.n_times)].copy()
    if len(pumps) == 0:
        return pd.DataFrame(columns=["trial","pump_number","theta_before_pump","theta_before_pump_Fp1","theta_before_pump_Fp2","frontal_asymmetry"])

    frontal_picks = [raw.ch_names.index(ch) for ch in FRONTAL_THETA_CHS if ch in raw.ch_names]
    fp1_pick = [raw.ch_names.index("Fp1")] if "Fp1" in raw.ch_names else []
    fp2_pick = [raw.ch_names.index("Fp2")] if "Fp2" in raw.ch_names else []

    rows = []
    for _, r in pumps.iterrows():
        s = int(r["sample"])
        pre_frontal = compute_theta_power_window(rtheta, s, -WIN200, 0.0, frontal_picks) if frontal_picks else np.nan
        pre_fp1 = compute_theta_power_window(rtheta, s, -WIN200, 0.0, fp1_pick) if fp1_pick else np.nan
        pre_fp2 = compute_theta_power_window(rtheta, s, -WIN200, 0.0, fp2_pick) if fp2_pick else np.nan
        fa = (np.log(pre_fp2 + 1e-12) - np.log(pre_fp1 + 1e-12)) if (np.isfinite(pre_fp1) and np.isfinite(pre_fp2)) else np.nan

        rows.append({
            "trial": int(r["trial"]),
            "pump_number": int(r["pump_number"]),
            "theta_before_pump": pre_frontal,
            "theta_before_pump_Fp1": pre_fp1,
            "theta_before_pump_Fp2": pre_fp2,
            "frontal_asymmetry": fa
        })

    return pd.DataFrame(rows)

def trial_theta_from_markers(raw, md, eeg_t0):
    sf = raw.info["sfreq"]
    rtheta = raw.copy().filter(THETA_BAND[0], THETA_BAND[1], picks="eeg", verbose=False)
    picks = [raw.ch_names.index(ch) for ch in FRONTAL_THETA_CHS if ch in raw.ch_names]
    if len(picks) == 0:
        return pd.DataFrame(columns=["trial","trial_mTheta","trial_SD_mThetaB"])

    starts = md[md["code"].astype(str).str.upper().eq("BART_TRIAL_START")].copy()
    ends = md[md["code"].astype(str).str.upper().isin(["BART_COLLECT","BART_EXPLODE"])].copy()
    if "trial" not in starts.columns or "trial" not in ends.columns:
        return pd.DataFrame(columns=["trial","trial_mTheta","trial_SD_mThetaB"])

    starts["trial"] = pd.to_numeric(starts["trial"], errors="coerce")
    ends["trial"] = pd.to_numeric(ends["trial"], errors="coerce")
    starts = starts.dropna(subset=["trial","lsltime"]).copy()
    ends = ends.dropna(subset=["trial","lsltime"]).copy()
    if len(starts) == 0 or len(ends) == 0:
        return pd.DataFrame(columns=["trial","trial_mTheta","trial_SD_mThetaB"])

    out = []
    for tnum, g0 in starts.groupby(starts["trial"].astype(int)):
        t_start = float(g0["lsltime"].min())
        g1 = ends[ends["trial"].astype(int) == int(tnum)]
        if len(g1) == 0:
            continue
        t_end = float(g1["lsltime"].min())
        if t_end <= t_start:
            continue

        s0 = lsltime_to_sample(t_start, eeg_t0, sf)
        s1 = lsltime_to_sample(t_end, eeg_t0, sf)
        s0 = max(s0, 0)
        s1 = min(s1, raw.n_times)
        if s1 <= s0 + int(sf * 0.2):
            continue

        seg = rtheta.get_data(picks=picks, start=s0, stop=s1)
        theta_ts = np.mean(seg**2, axis=0)

        out.append({
            "trial": int(tnum),
            "trial_mTheta": float(np.mean(theta_ts)),
            "trial_SD_mThetaB": float(np.std(theta_ts, ddof=1)),
        })

    return pd.DataFrame(out)


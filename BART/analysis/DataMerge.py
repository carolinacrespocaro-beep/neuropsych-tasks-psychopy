def build_raw_from_xdf_eeg(eeg_stream):
    data = np.asarray(eeg_stream["time_series"])
    t = np.asarray(eeg_stream["time_stamps"], dtype=float)
    if data.ndim == 1:
        data = data[:, None]
    n_samp, n_ch = data.shape

    sfreq_est = 1.0 / np.median(np.diff(t))
    ch_names = EEG_ORDER[:n_ch] if n_ch <= len(EEG_ORDER) else [f"EEG{ii+1:02d}" for ii in range(n_ch)]
    arr = data.T.astype(float)

    peak = float(np.nanmax(np.abs(arr)))
    if peak > 1e3:
        arr *= 1e-6
    elif peak > 5.0:
        arr *= 1e-3

    info = mne.create_info(ch_names=ch_names, sfreq=sfreq_est, ch_types=["eeg"] * n_ch)
    raw = mne.io.RawArray(arr, info, verbose=False)
    return raw, t


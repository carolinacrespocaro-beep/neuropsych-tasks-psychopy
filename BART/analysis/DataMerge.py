def theta_before_each_pump(raw, md, eeg_t0):
    pumps = md[md["code"].astype(str).str.upper().eq("BART_PUMP")].copy()
    if len(pumps) == 0 or ("trial" not in pumps.columns) or ("pump" not in pumps.columns):
        return pd.DataFrame(columns=["trial","pump_number","theta_before_pump","theta_before_pump_Fp1","theta_before_pump_Fp2","frontal_asymmetry"])

    rtheta = raw.copy().filter(THETA_BAND[0], THETA_BAND[1], picks="eeg", verbose=False)
    sf = raw.info["sfreq"]

    pumps["trial"] = pd.to_numeric(pumps["trial"], errors="coerce")
    pumps["pump_number"] = pd.to_numeric(pumps["pump"], errors="coerce")
    pumps = pumps.dropna(subset=["trial","pump_number","lsltime"]).copy()

    pumps["trial"] = pumps["trial"].astype(int)
    pumps["pump_number"] = pumps["pump_number"].astype(int)
    pumps["sample"] = pumps["lsltime"].apply(lambda t: lsltime_to_sample(float(t), eeg_t0, sf)).astype(int)

    min_samp = int(np.ceil(WIN200 * sf))
    pumps = pumps[(pumps["sample"] >= min_samp) & (pumps["sample"] < raw.n_times)].copy()
    if len(pumps) == 0:
        return pd.DataFrame(columns=["trial","pump_number","theta_before_pump","theta_before_pump_Fp1","theta_before_pump_Fp2","frontal_asymmetry"])

    frontal_picks = [raw.ch_names.index(ch) for ch in FRONTAL_THETA_CHS if ch in raw.ch_names]
    fp1_pick = [raw.ch_names.index("Fp1")] if "Fp1" in raw.ch_names else []
    fp2_pick = [raw.ch_names.index("Fp2")] if "Fp2" in raw.ch_names else []

    rows = []
    for _, r in pumps.iterrows():
        s = int(r["sample"])
        pre_frontal = compute_theta_power_window(rtheta, s, -WIN200, 0.0, frontal_picks) if frontal_picks else np.nan
        pre_fp1 = compute_theta_power_window(rtheta, s, -WIN200, 0.0, fp1_pick) if fp1_pick else np.nan
        pre_fp2 = compute_theta_power_window(rtheta, s, -WIN200, 0.0, fp2_pick) if fp2_pick else np.nan
        fa = (np.log(pre_fp2 + 1e-12) - np.log(pre_fp1 + 1e-12)) if (np.isfinite(pre_fp1) and np.isfinite(pre_fp2)) else np.nan

        rows.append({
            "trial": int(r["trial"]),
            "pump_number": int(r["pump_number"]),
            "theta_before_pump": pre_frontal,
            "theta_before_pump_Fp1": pre_fp1,
            "theta_before_pump_Fp2": pre_fp2,
            "frontal_asymmetry": fa
        })

    return pd.DataFrame(rows)

def trial_theta_from_markers(raw, md, eeg_t0):
    sf = raw.info["sfreq"]
    rtheta = raw.copy().filter(THETA_BAND[0], THETA_BAND[1], picks="eeg", verbose=False)
    picks = [raw.ch_names.index(ch) for ch in FRONTAL_THETA_CHS if ch in raw.ch_names]
    if len(picks) == 0:
        return pd.DataFrame(columns=["trial","trial_mTheta","trial_SD_mThetaB"])

    starts = md[md["code"].astype(str).str.upper().eq("BART_TRIAL_START")].copy()
    ends = md[md["code"].astype(str).str.upper().isin(["BART_COLLECT","BART_EXPLODE"])].copy()
    if "trial" not in starts.columns or "trial" not in ends.columns:
        return pd.DataFrame(columns=["trial","trial_mTheta","trial_SD_mThetaB"])

    starts["trial"] = pd.to_numeric(starts["trial"], errors="coerce")
    ends["trial"] = pd.to_numeric(ends["trial"], errors="coerce")
    starts = starts.dropna(subset=["trial","lsltime"]).copy()
    ends = ends.dropna(subset=["trial","lsltime"]).copy()
    if len(starts) == 0 or len(ends) == 0:
        return pd.DataFrame(columns=["trial","trial_mTheta","trial_SD_mThetaB"])

    out = []
    for tnum, g0 in starts.groupby(starts["trial"].astype(int)):
        t_start = float(g0["lsltime"].min())
        g1 = ends[ends["trial"].astype(int) == int(tnum)]
        if len(g1) == 0:
            continue
        t_end = float(g1["lsltime"].min())
        if t_end <= t_start:
            continue

        s0 = lsltime_to_sample(t_start, eeg_t0, sf)
        s1 = lsltime_to_sample(t_end, eeg_t0, sf)
        s0 = max(s0, 0)
        s1 = min(s1, raw.n_times)
        if s1 <= s0 + int(sf * 0.2):
            continue

        seg = rtheta.get_data(picks=picks, start=s0, stop=s1)
        theta_ts = np.mean(seg**2, axis=0)

        out.append({
            "trial": int(tnum),
            "trial_mTheta": float(np.mean(theta_ts)),
            "trial_SD_mThetaB": float(np.std(theta_ts, ddof=1)),
        })

    return pd.DataFrame(out)


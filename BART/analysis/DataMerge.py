def parse_bids_bits(name: str):
    base = Path(name).name
    sub = re.search(r"sub-([A-Za-z0-9]+)", base)
    ses = re.search(r"ses-([A-Za-z0-9]+)", base)
    run = re.search(r"run-([0-9]+)", base)
    task = re.search(r"task-([A-Za-z0-9]+)", base)
    cond = re.search(r"cond-([A-Za-z0-9_]+)", base)

    out = {
        "sub": sub.group(1) if sub else None,
        "ses": ses.group(1) if ses else None,
        "run": run.group(1) if run else None,
        "task": task.group(1) if task else None,
        "condition": cond.group(1) if cond else None,
    }
    if out["ses"] is not None:
        m = re.search(r"(\d+)", out["ses"])
        out["ses_num"] = int(m.group(1)) if m else np.nan
    else:
        out["ses_num"] = np.nan
    return out

def read_beh_sheets(fp: Path):
    xls = pd.ExcelFile(fp)
    sheets = {}
    for sh in xls.sheet_names:
        df = pd.read_excel(fp, sheet_name=sh)
        df.columns = [str(c).strip() for c in df.columns]
        sheets[sh.lower()] = df
    return sheets

def get_sheet(sheets: dict, candidates):
    for c in candidates:
        if c in sheets:
            return sheets[c]
    return None

